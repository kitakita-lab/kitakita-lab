/**
 * News データ。
 *
 * 将来的なCMS化を想定したデータ構造です。
 * `body` は段落の配列で、各お知らせの詳細ページに表示されます。
 * CMS導入時は、この配列を API レスポンス（同じ型）に置き換えるだけで移行できます。
 */

export type NewsCategory = 'お知らせ' | 'プレスリリース' | 'イベント' | 'メディア'

export type NewsItem = {
  /** URL スラッグ（/news/:slug） */
  slug: string
  title: string
  /**
   * タイトルを意味の単位で区切ったもの（表示専用）。各単位の内側では折り返さず、
   * 単位の境目でだけ折り返す。狭幅で「フラワ／ーボトル」のように語中で割れないため。
   * 各単位は 9 文字以内にする（詳細ページの見出し 30px が 320px 幅で 1 行に収まる長さ）。
   */
  titleSegments?: string[]
  /** ISO 形式の日付（YYYY-MM-DD）。並び順の基準に使う。 */
  date: string
  /**
   * 日付の代わりに表示するラベル。正式な公開日が未確定のお知らせは
   * '公開準備中' などを設定し、確定していない日付を公開面に出さない。
   */
  dateLabel?: string
  category: NewsCategory
  excerpt: string
  /** 詳細本文（段落の配列） */
  body: string[]
}

