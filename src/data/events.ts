/**
 * 「ひとつのブランドの、歩み」（/events 一覧に表示）。
 *
 * ここに並ぶ実績を、ikyu というひとつのブランドの歩みとしてつなぐ
 * タイムライン。規模の成長物語ではなく、「いま持っているものから、
 * 少し違う可能性を試していったら、活動できる場所や組み合わせが
 * 広がっていった」ことを伝えるのが目的。
 *
 * 主語は ikyu。KitaKita Lab は「その一歩を一緒に考え、かたちにする」
 * 距離感を守ること。開催前のイベントは「次の挑戦」以上に評価しない。
 * 新しい一歩が増えたら、末尾に要素を追加する。
 */
export type JourneyStep = {
  /** 時期の表示ラベル（例: 'これまで' '2026年6月' '予定'） */
  period: string
  title: string
  body: string
  /** 対応する実績詳細への slug（実績ページがある場合のみ） */
  slug?: string
  /** 開催前の「次の挑戦」は true（リンクなし・控えめな表示） */
  upcoming?: boolean
}

