/**
 * イベント実績データ。
 *
 * ─────────────────────────────────────────────────
 * ■ 新しい実績の追加方法（テンプレート）
 *
 * 1. 写真を `public/events/<slug>/` に置く
 *    （ヒーロー1枚 + ギャラリー数枚。横長・1200〜1800px程度を推奨）
 * 2. 下の `events` 配列に、既存の要素をコピーして内容を書き換えた
 *    オブジェクトを追加する
 *
 * これだけで一覧ページ（/events）のカードと
 * 詳細ページ（/events/<slug>）が自動的に生成されます。
 * `?` 付きの項目は省略可能で、省略したセクションは表示されません。
 *
 * ※ 掲載前チェック：クライアント向け報告書の数値（成約件数など）、
 *   提出先企業名、運営改善提案は掲載しない。写真は写り込んだ方の
 *   肖像権・掲示物の権利に配慮して選定する。
 * ─────────────────────────────────────────────────
 */

export type EventCategory =
  | '商業施設'
  | '公共空間'
  | '企業コラボ'
  | '自治体'
  | '教育機関'
  | 'ワークショップ'

export type EventPhoto = {
  /** public/ 以下の画像パス */
  src: string
  alt: string
  caption?: string
}

export type EventStat = {
  /** 例: '117組' */
  value: string
  /** 例: '総参加組数' */
  label: string
}

export type EventSection = {
  heading: string
  body: string[]
  /** チェックリスト形式で見せたいポイント */
  points?: string[]
}

export type EventDayReport = {
  /** 例: 'Day 1' */
  label: string
  /** 例: '8月1日（土）' */
  date: string
  body: string
}

export type EventVoice = {
  quote: string
  /** 例: 'ご参加のお客様' */
  context: string
}

export type EventReport = {
  /** URL スラッグ（/events/:slug） */
  slug: string
  title: string
  category: EventCategory
  /** 並び替え用の ISO 日付（開催初日） */
  dateISO: string
  /** 表示用の会期 */
  dateLabel: string
  venue: string
  /** 一覧カード・SEO 用の要約（2〜3文） */
  excerpt: string
  heroImage?: EventPhoto
  /**
   * スマホ幅（640px未満）専用のヒーロー画像。元写真が縦位置で、横長の
   * トリミングでは展示の内容が伝わらない場合にのみ指定する。指定した
   * イベントだけ、スマホは 4:5・PC は 3:2 で表示される（未指定の
   * イベントは従来どおり 16:9 のまま）。
   */
  heroImageMobile?: { src: string }
  /**
   * 一覧カード用に、タイトルを意味の単位（1行目＝企画名/会場名、
   * 2行目＝実施内容）で明示的に2行に分けたもの。未指定なら title を
   * そのまま表示する。title 自体（詳細ページの h1・SEO）は変更しない。
   */
  titleLines?: [string, string]
  /**
   * 一覧カードのサムネイル（16:10・object-cover）で heroImage のどこを
   * 見せるかの object-position。未指定なら中央。詳細ページの Hero には
   * 影響しない。例: 'center 80%'
   */
  cardImagePosition?: string
  /** 開催概要（表形式で表示） */
  overview: { label: string; value: string }[]
  /** 参加実績などの数字ハイライト */
  stats?: EventStat[]
  /** 本文セクション（イベント概要・ワークショップ内容など） */
  sections?: EventSection[]
  /** 日別の当日の様子 */
  dayReports?: EventDayReport[]
  /** フォトギャラリー */
  photos?: EventPhoto[]
  /** 参加者の反応 */
  voices?: EventVoice[]
  /** KitaKita Labとして大切にしていること */
  commitments?: { title: string; body: string }[]
}

